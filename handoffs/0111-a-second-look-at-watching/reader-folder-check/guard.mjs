// Reader's script: copies the five real records into a temp record root and asks the corrected runner's guard about checkouts and records that differ; writes only under the temp folder.
//   node guard.mjs <a checkout with the corrected runner> <runs' checkout>
import { cpSync, mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const [co, runs] = process.argv.slice(2);
const r = await import(join(co, "scripts/lib/watching-second-look-paid.mjs"));
const fresh = () => { const t = mkdtempSync(join(tmpdir(), "reader-guard-")); cpSync(join(runs, "experiments/watching/second-look/opus"), join(t, "opus"), { recursive: true }); return t; };
const now = r.checkout();
const say = (what, n, root) => console.log(`${what}: refused=${JSON.stringify(r.madeFromAnother(n, root)?.what ?? null)} counted-as-same=${r.madeWithTheEarlierRunner(n, root)?.runs.length ?? 0}`);
const edit = (root, name, fn) => { const p = join(root, name, "result.json"); const j = JSON.parse(readFileSync(p, "utf8")); fn(j); writeFileSync(p, JSON.stringify(j)); };
let t = fresh();
console.log(`this checkout: hook ${now.hook_sha256?.slice(0, 8)} tool ${now.tool_sha256?.slice(0, 8)} runner ${now.runner_sha256?.slice(0, 8)}`);
say("1 the five real records, this runner", now, t);
say("2 the five real records, ANY other runner (ffff…)", { ...now, runner_sha256: "f".repeat(64) }, t);
say("3 the five real records, a runner whose checksum could not be made (null)", { ...now, runner_sha256: null }, t);
say("4 another hook", { ...now, hook_sha256: "0".repeat(64) }, t);
say("5 another tool", { ...now, tool_sha256: "0".repeat(64) }, t);
say("6 another version", { ...now, grooph_version: "9.9.9" }, t);
say("6b tool checksum null (dist unreadable)", { ...now, tool_sha256: null }, t);
edit(t, "opus/four/plain-1", (j) => { j.given.the_runners_checkout.hook_sha256 = "1".repeat(64); });
say("7 a record of the earlier runner with another hook", now, t);
rmSync(t, { recursive: true }); t = fresh();
edit(t, "opus/six/plain-1", (j) => { delete j.given.the_runners_checkout.hook_sha256; j.given.the_runners_checkout.runner_sha256 = "2".repeat(64); j.given.the_runners_checkout.tool_sha256 = "3".repeat(64); });
say("8 a record with no hook checksum, and another runner and tool (passed over whole)", now, t);
rmSync(t, { recursive: true }); t = fresh();
edit(t, "opus/six/plain-1", (j) => { delete j.given.the_runners_checkout.tool_sha256; delete j.given.the_runners_checkout.grooph_version; });
say("9 a record of the earlier runner with no tool checksum and no version", now, t);
rmSync(t, { recursive: true }); t = fresh();
cpSync(join(t, "opus/four/outside-1"), join(t, "opus/four/outside-1-rerun"), { recursive: true });
say("10 with a rerun record by the earlier runner", now, t);
edit(t, "opus/four/outside-1-rerun", (j) => { j.given.the_runners_checkout.runner_sha256 = "4".repeat(64); });
say("11 with a rerun record by a third runner", now, t);
rmSync(t, { recursive: true }); t = fresh();
mkdirSync(join(t, "opus/six/outside-1"), { recursive: true });
writeFileSync(join(t, "opus/six/outside-1/result.json"), JSON.stringify({ given: { the_runners_checkout: { ...now, another_than_a_run_before: null } } }));
say("12 five by the earlier runner and a sixth by this one, asked of this one", now, t);
say("13 the same six, asked of a THIRD runner", { ...now, runner_sha256: "f".repeat(64) }, t);
rmSync(t, { recursive: true }); t = fresh();
edit(t, "opus/four/plain-1", (j) => { j.given.the_runners_checkout.runner_sha256 = "E70AA3A0ADCDE19564DC2514CD4C0BE7D0C5169F3714004FFBB08754CB8D153A"; });
say("14 the earlier runner's checksum in capitals in one record", now, t);
edit(t, "opus/four/plain-1", (j) => { j.given.the_runners_checkout.runner_sha256 = "constructor"; });
say("15 a record whose runner is the word constructor", now, t);
edit(t, "opus/four/plain-1", (j) => { j.given.the_runners_checkout = { hook_sha256: now.hook_sha256, runner_sha256: "e70aa3a0adcde19564dc2514cd4c0be7d0c5169f3714004ffbb08754cb8d153a" }; });
say("16 a hand-made record: only this hook and the earlier runner's checksum", { ...now, runner_sha256: "f".repeat(64) }, t);
rmSync(t, { recursive: true });

#!/usr/bin/env node
/**
 * Generate docs/cli.md: the CLI, command by command, from the help text the CLI itself prints.
 * The overview is `grooph --help`; each command's section is `grooph help <command>`, in the overview's order.
 *
 *   node scripts/cli-reference.mjs           write it
 *   node scripts/cli-reference.mjs --check   exit 1 when it is stale or missing (CI)
 *
 * Needs @grooph/cli built (`pnpm -r build`). The text comes from the same `run` the `grooph` command calls, so
 * this page cannot drift from what a person sees at a terminal. Change a command's help in packages/cli and run
 * this again.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cli = await import(join(root, "packages/cli/dist/src/index.js")).catch(() => {
  console.error("cli-reference: @grooph/cli is not built; run `pnpm -r build` first");
  process.exit(2);
});

const problems = [];

/** What `grooph <args>` prints to its output, through the CLI's own entry point. */
async function grooph(...args) {
  const lines = [];
  const errors = [];
  const code = await cli.run(args, { out: (line) => lines.push(line), err: (line) => errors.push(line) });
  if (code !== 0) problems.push(`grooph ${args.join(" ")} exited ${code}: ${errors.join(" ")}`);
  return lines.join("\n").replace(/[ \t]+$/gm, "").trim();
}

// The overview's first line carries the version. Left in, this page would be one more place the version is
// written, stale on the day of every release.
const versioned = `grooph ${cli.VERSION}: `;
let overview = await grooph("--help");
if (!overview.startsWith(versioned)) problems.push(`the overview no longer starts with "${versioned}"`);
overview = `grooph: ${overview.slice(versioned.length)}`;

/** The overview's groups and commands: a heading is a line with no indent and no spaces, a command a line indented by two. */
const groups = [];
for (const line of overview.split("\n")) {
  const command = /^  ([a-z][a-z-]*)\s+(\S.*)$/.exec(line);
  if (/^[A-Z][a-z]+$/.test(line)) groups.push({ title: line, commands: [] });
  else if (command && groups.length > 0) groups.at(-1).commands.push({ name: command[1], summary: command[2] });
}
const commands = groups.flatMap((group) => group.commands);
// A page with no commands on it would still be "current": what cannot be read is a failure, not an empty page.
if (commands.length === 0) problems.push("no command could be read from `grooph --help`");

const fence = (text) => `\`\`\`text\n${text}\n\`\`\``;
const sentence = (text) => `${text.charAt(0).toUpperCase()}${text.slice(1)}${/[.)]$/.test(text) ? "" : "."}`;

let out = `# The CLI, command by command

\`grooph\` authors, checks and compiles multi-agent loop graphs and operation maps from a terminal. It never runs them: the harness does. Every command below is shown with the help it prints itself, \`grooph help <command>\`, in the order \`grooph --help\` lists them. New here? Start with the [quickstart](quickstart.md).

_Generated by \`scripts/cli-reference.mjs\` from the CLI's own help text. Do not edit it; CI fails when it is stale._

${fence(overview)}
`;

for (const group of groups) {
  for (const { name, summary } of group.commands) {
    const page = await grooph("help", name);
    if (page === "") problems.push(`grooph help ${name} printed nothing`);
    out += `\n## \`grooph ${name}\`\n\n${sentence(summary)}\n\n${fence(page)}\n`;
  }
}

if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const path = join(root, "docs/cli.md");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current !== out) {
    console.error("stale: docs/cli.md; run `pnpm -r build && node scripts/cli-reference.mjs` and commit the result");
    process.exit(1);
  }
  console.log("docs/cli.md is current");
} else {
  writeFileSync(path, out);
  console.log(`wrote docs/cli.md (${commands.length} commands)`);
}

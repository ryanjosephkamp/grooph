#!/usr/bin/env node
/**
 * Generate docs/rules.md: one section per validation rule code, from the rule tables in
 * docs/graph-ir.md §3 and docs/operation-map.md §3 and from the fixtures, with what the validator
 * prints for a failing fixture and a passing one that validates clean.
 *
 *   node scripts/rule-reference.mjs           write it
 *   node scripts/rule-reference.mjs --check   exit 1 when it is stale or missing (CI)
 *
 * Needs @grooph/core built (`pnpm -r build`). The printed lines come from the same functions the
 * CLI uses (`validate`, `validateMap`, `formatIssue`), so this page cannot drift from them.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const core = await import(join(root, "packages/core/dist/src/index.js")).catch(() => {
  console.error("rule-reference: @grooph/core is not built; run `pnpm -r build` first");
  process.exit(2);
});
const { parseGraphText, validate, parseMapText, validateMap, formatIssue, hasErrors } = core;

const read = (rel) => readFileSync(join(root, rel), "utf8");
const problems = [];

/** `| \`CODE\` | text |` rows of a document, in order. */
const rules = (doc) =>
  [...read(doc).matchAll(/^\| `([EW]_[A-Z_]+)` \| (.+) \|$/gm)].map((m) => ({ code: m[1], text: m[2].replace(/\s+/g, " ").trim() }));

const graphIssues = (rel, forExport = true) => {
  const parsed = parseGraphText(read(rel));
  return parsed.doc ? validate(parsed.doc, { forExport }) : parsed.issues;
};
const mapIssues = (rel) => {
  const parsed = parseMapText(read(rel));
  // A `graph` pointer that is a path is looked up beside the map, as `grooph validate` does.
  const resolveGraph = (ref) => {
    if (/^[a-z][a-z0-9+.-]*:\/\//i.test(ref) || !/\.json$/i.test(ref)) return undefined;
    const path = join(root, dirname(rel), ref);
    return existsSync(path) && parseGraphText(readFileSync(path, "utf8")).doc !== undefined;
  };
  return parsed.map ? validateMap(parsed.map, { resolveGraph }) : parsed.issues;
};

const kinds = [
  {
    title: "Graph documents",
    intro: "Checked by `grooph validate <file>`; `--for-export` adds `E_NO_TARGET` and `E_NO_GOAL`. The rules are defined in [graph-ir.md](graph-ir.md) §3.",
    doc: "docs/graph-ir.md",
    invalid: "fixtures/invalid",
    passing: "fixtures/valid/fix-until-green.grooph.json",
    suffix: ".grooph.json",
    issues: graphIssues,
  },
  {
    title: "Operation maps",
    intro: "Checked by `grooph validate <file>` on a `*.grooph-map.json`. The rules are defined in [operation-map.md](operation-map.md) §3.",
    doc: "docs/operation-map.md",
    invalid: "fixtures/maps/invalid",
    passing: "fixtures/maps/valid/two-sessions.grooph-map.json",
    suffix: ".grooph-map.json",
    issues: mapIssues,
  },
];

const fence = (lines) => `\`\`\`text\n${lines.join("\n")}\n\`\`\``;
let out = `# Rule reference

Every validation rule, by its stable code: what it says, what \`grooph validate\` prints when it fires, a document that fires it and one that does not. \`E_…\` is an error and blocks export; \`W_…\` is a warning, shown and carried into the lead brief.

_Generated by \`scripts/rule-reference.mjs\` from the rule tables and \`fixtures/\`. Do not edit it; CI fails when it is stale._
`;

for (const kind of kinds) {
  const passingIssues = kind.issues(kind.passing);
  if (passingIssues.length > 0) problems.push(`${kind.passing} was meant to validate clean but reports ${passingIssues.map((i) => i.code).join(", ")}`);
  out += `\n## ${kind.title}\n\n${kind.intro}\n`;
  for (const { code, text } of rules(kind.doc)) {
    const folder = join(kind.invalid, code);
    const files = existsSync(join(root, folder))
      ? readdirSync(join(root, folder)).filter((name) => name.endsWith(kind.suffix)).sort()
      : [];
    out += `\n### \`${code}\`\n\n${text}\n`;
    if (files.length === 0) {
      problems.push(`${code} has no failing fixture under ${folder}`);
      continue;
    }
    const failing = `${folder}/${files[0]}`;
    const hits = kind.issues(failing).filter((issue) => issue.code === code);
    if (hits.length === 0) problems.push(`${failing} does not report ${code}`);
    out += `\n**Fails:** [\`${failing}\`](../${failing}) prints\n\n${fence(hits.map((issue) => formatIssue(issue)))}\n`;
    out += `\n**Passes:** [\`${kind.passing}\`](../${kind.passing}) validates with ${hasErrors(passingIssues) ? "errors" : "no issues"}.\n`;
  }
}

if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const path = join(root, "docs/rules.md");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current !== out) {
    console.error("stale: docs/rules.md; run `node scripts/rule-reference.mjs` and commit the result");
    process.exit(1);
  }
  console.log("docs/rules.md is current");
} else {
  writeFileSync(path, out);
  console.log(`wrote docs/rules.md (${(out.match(/^### /gm) ?? []).length} rules)`);
}
